function getByPath(object, path) {
  return path.split('.').reduce((current, segment) => current?.[segment], object);
}

function setTextContent(element, value) {
  if (typeof value === 'string') {
    element.innerHTML = value;
  }
}

let activeLanguage = 'de';

function readStoredLanguage() {
  try {
    return localStorage.getItem('portfolio-lang');
  } catch {
    return null;
  }
}

function storeLanguage(language) {
  try {
    localStorage.setItem('portfolio-lang', language);
  } catch {
    // The URL parameter remains the shareable source of truth.
  }
}

function updateLanguageUrl(language) {
  try {
    const url = new URL(window.location.href);
    url.searchParams.set('lang', language);
    window.history.replaceState({}, '', url);
  } catch {
    // Language switching still works when URL APIs are unavailable.
  }
}

function updatePageMetadata(active, language) {
  const isPrivacyPage = document.body.dataset.page === 'privacy';
  const description = isPrivacyPage ? active.privacy.metaDescription : active.metaDescription;
  const title = isPrivacyPage ? active.privacy.documentTitle : active.documentTitle;
  const siteOrigin = 'https://yannikberner-ai-pm.github.io';
  const localizedUrl = `${siteOrigin}/?lang=${language}`;

  document.title = title;
  document.querySelector('meta[name="description"]')?.setAttribute('content', description);

  if (!isPrivacyPage) {
    document.querySelector('link[rel="canonical"]')?.setAttribute('href', localizedUrl);
    document.querySelector('meta[property="og:url"]')?.setAttribute('content', localizedUrl);
    document.querySelector('meta[property="og:title"]')?.setAttribute('content', title);
    document.querySelector('meta[property="og:description"]')?.setAttribute('content', active.socialDescription);
    document.querySelector('meta[property="og:locale"]')?.setAttribute('content', language === 'en' ? 'en_GB' : 'de_DE');
    document.querySelector('meta[property="og:image:alt"]')?.setAttribute('content', active.socialImageAlt);
    document.querySelector('meta[name="twitter:title"]')?.setAttribute('content', title);
    document.querySelector('meta[name="twitter:description"]')?.setAttribute('content', active.socialDescription);
    document.querySelector('meta[name="twitter:image:alt"]')?.setAttribute('content', active.socialImageAlt);

    const jsonLd = document.getElementById('person-jsonld');
    if (jsonLd && active.personDescription) {
      try {
        const data = JSON.parse(jsonLd.textContent);
        data.description = active.personDescription;
        data.url = localizedUrl;
        jsonLd.textContent = JSON.stringify(data, null, 2);
      } catch {
        // Keep static JSON-LD if parsing fails.
      }
    }
  }
}

function updateTranslations(language) {
  const active = translations[language] || translations.de;
  activeLanguage = language;
  document.documentElement.lang = language;
  updatePageMetadata(active, language);

  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const value = getByPath(active, element.getAttribute('data-i18n'));
    // Keep HTML fallback when a key is missing (e.g. stale cached script.js).
    setTextContent(element, value);
  });

  document.querySelectorAll('[data-i18n-alt]').forEach((element) => {
    const value = getByPath(active, element.getAttribute('data-i18n-alt'));
    if (value !== undefined) {
      element.setAttribute('alt', value);
    }
  });

  document.querySelectorAll('[data-i18n-aria]').forEach((element) => {
    const value = getByPath(active, element.getAttribute('data-i18n-aria'));
    if (value !== undefined) {
      element.setAttribute('aria-label', value);
    }
  });

  document.querySelectorAll('.lang-button').forEach((button) => {
    const isActive = button.getAttribute('data-lang') === language;
    button.classList.toggle('is-active', isActive);
    button.setAttribute('aria-pressed', String(isActive));
  });

  document.querySelectorAll('[data-url-de][data-url-en]').forEach((link) => {
    const localizedUrl = language === 'en' ? link.dataset.urlEn : link.dataset.urlDe;
    if (localizedUrl) {
      link.setAttribute('href', localizedUrl);
    }
  });

  document.querySelectorAll('[data-portfolio-link]').forEach((link) => {
    link.setAttribute('href', `index.html?lang=${language}`);
  });

  document.querySelectorAll('[data-privacy-link]').forEach((link) => {
    link.setAttribute('href', `datenschutz.html?lang=${language}`);
  });

  document.querySelectorAll('.details-toggle').forEach((button) => {
    const expanded = button.getAttribute('aria-expanded') === 'true';
    const labels = getDetailsToggleLabels(active, button.dataset.toggleKind);
    button.textContent = expanded ? labels.hide : labels.show;
  });
}

function getDetailsToggleLabels(active, toggleKind) {
  if (toggleKind === 'narrative') {
    return {
      show: active.projects.common.viewNarrative,
      hide: active.projects.common.hideNarrative
    };
  }

  return {
    show: active.experience.common.viewDetails,
    hide: active.experience.common.hideDetails
  };
}

function setLanguage(language) {
  if (!translations[language]) {
    return;
  }

  storeLanguage(language);
  updateLanguageUrl(language);
  updateTranslations(language);
}

document.addEventListener('DOMContentLoaded', () => {
  document.documentElement.classList.add('js-ready');
  const navToggle = document.querySelector('.nav-toggle');
  const siteNav = document.querySelector('.site-nav');
  const urlLanguage = new URLSearchParams(window.location.search).get('lang');
  const storedLanguage = readStoredLanguage();
  const initialLanguage = urlLanguage === 'en' || urlLanguage === 'de'
    ? urlLanguage
    : storedLanguage === 'en'
      ? 'en'
      : 'de';

  setLanguage(initialLanguage);

  if (navToggle && siteNav) {
    navToggle.addEventListener('click', () => {
      const expanded = navToggle.getAttribute('aria-expanded') === 'true';
      navToggle.setAttribute('aria-expanded', String(!expanded));
      siteNav.classList.toggle('is-open');
    });

    document.addEventListener('keydown', (event) => {
      if (event.key === 'Escape' && siteNav.classList.contains('is-open')) {
        navToggle.setAttribute('aria-expanded', 'false');
        siteNav.classList.remove('is-open');
        navToggle.focus();
      }
    });

    siteNav.querySelectorAll('a, .lang-button').forEach((link) => {
      link.addEventListener('click', () => {
        if (window.innerWidth <= 960) {
          navToggle.setAttribute('aria-expanded', 'false');
          siteNav.classList.remove('is-open');
        }
      });
    });
  }

  document.querySelectorAll('.lang-button').forEach((button) => {
    button.addEventListener('click', () => {
      const lang = button.getAttribute('data-lang');
      if (lang) {
        setLanguage(lang);
      }
    });
  });

  document.querySelectorAll('a[href^="#"]').forEach((link) => {
    link.addEventListener('click', (event) => {
      const targetId = link.getAttribute('href');
      if (!targetId || targetId === '#') {
        return;
      }

      const target = document.querySelector(targetId);
      if (!target) {
        return;
      }

      event.preventDefault();
      const reduceMotion = window.matchMedia?.('(prefers-reduced-motion: reduce)').matches;
      target.scrollIntoView({ behavior: reduceMotion ? 'auto' : 'smooth', block: 'start' });

      const focusSelector = link.getAttribute('data-focus-target');
      const focusTarget = focusSelector ? document.querySelector(focusSelector) : null;
      if (!focusTarget) {
        return;
      }

      const focusAfterScroll = () => {
        if (typeof focusTarget.focus === 'function') {
          focusTarget.focus({ preventScroll: true });
        }
      };

      if (reduceMotion) {
        focusAfterScroll();
        return;
      }

      window.setTimeout(focusAfterScroll, 450);
    });
  });

  const revealItems = document.querySelectorAll('.reveal');
  if ('IntersectionObserver' in window) {
    const revealObserver = new IntersectionObserver(
      (entries) => {
        entries.forEach((entry) => {
          if (entry.isIntersecting) {
            entry.target.classList.add('is-visible');
            revealObserver.unobserve(entry.target);
          }
        });
      },
      { threshold: 0.15 }
    );

    revealItems.forEach((item) => revealObserver.observe(item));
  } else {
    revealItems.forEach((item) => item.classList.add('is-visible'));
  }

  const sections = document.querySelectorAll('main section[id]');
  const navLinks = Array.from(document.querySelectorAll('.site-nav a[href^="#"]'));
  if ('IntersectionObserver' in window) {
    const currentObserver = new IntersectionObserver(
      (entries) => {
        entries.forEach((entry) => {
          if (!entry.isIntersecting) {
            return;
          }

          navLinks.forEach((link) => {
            const isActive = link.getAttribute('href') === `#${entry.target.id}`;
            link.classList.toggle('active', isActive);
            if (isActive) {
              link.setAttribute('aria-current', 'location');
            } else {
              link.removeAttribute('aria-current');
            }
          });
        });
      },
      { rootMargin: '-35% 0px -50% 0px', threshold: 0.1 }
    );

    sections.forEach((section) => currentObserver.observe(section));
  }

  document.querySelectorAll('.portrait-shell img, .media-shell img').forEach((image) => {
    image.addEventListener('error', () => {
      image.style.display = 'none';
      const shell = image.closest('.portrait-shell, .media-shell');
      if (shell) {
        shell.classList.add('image-missing');
      }
    });
  });

  document.querySelectorAll('.details-toggle').forEach((button) => {
    let capturedScrollY = null;

    button.addEventListener('pointerdown', () => {
      capturedScrollY = window.scrollY;
    });

    button.addEventListener('click', () => {
      const scrollY = capturedScrollY !== null ? capturedScrollY : window.scrollY;
      capturedScrollY = null;

      const expanded = button.getAttribute('aria-expanded') === 'true';
      const targetId = button.getAttribute('aria-controls');
      const target = targetId ? document.getElementById(targetId) : null;

      button.setAttribute('aria-expanded', String(!expanded));
      const active = translations[activeLanguage] || translations.de;
      const labels = getDetailsToggleLabels(active, button.dataset.toggleKind);
      button.textContent = expanded ? labels.show : labels.hide;

      if (target) {
        target.hidden = expanded;
      }

      window.scrollTo(0, scrollY);
      requestAnimationFrame(() => window.scrollTo(0, scrollY));
    });
  });

  document.querySelectorAll('details > summary').forEach((summary) => {
    let capturedScrollY = null;

    summary.addEventListener('pointerdown', () => {
      capturedScrollY = window.scrollY;
    });

    summary.addEventListener('click', (event) => {
      event.preventDefault();
      const details = summary.parentElement;
      const scrollY = capturedScrollY !== null ? capturedScrollY : window.scrollY;
      capturedScrollY = null;
      details.open = !details.open;
      window.scrollTo(0, scrollY);
      requestAnimationFrame(() => window.scrollTo(0, scrollY));
    });
  });
});
